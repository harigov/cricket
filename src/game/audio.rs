const SR: u32 = 44100;

fn wav_bytes(samples: &[f32], sample_rate: u32) -> Vec<u8> {
    let n = samples.len() as u32;
    let byte_rate = sample_rate * 2;
    let data_size = n * 2;
    let mut out = Vec::with_capacity(44 + data_size as usize);
    out.extend_from_slice(b"RIFF");
    out.extend_from_slice(&(36 + data_size).to_le_bytes());
    out.extend_from_slice(b"WAVE");
    out.extend_from_slice(b"fmt ");
    out.extend_from_slice(&16u32.to_le_bytes());
    out.extend_from_slice(&1u16.to_le_bytes());
    out.extend_from_slice(&1u16.to_le_bytes());
    out.extend_from_slice(&sample_rate.to_le_bytes());
    out.extend_from_slice(&byte_rate.to_le_bytes());
    out.extend_from_slice(&2u16.to_le_bytes());
    out.extend_from_slice(&16u16.to_le_bytes());
    out.extend_from_slice(b"data");
    out.extend_from_slice(&data_size.to_le_bytes());
    for &s in samples {
        let v = (s.clamp(-1.0, 1.0) * 32767.0) as i16;
        out.extend_from_slice(&v.to_le_bytes());
    }
    out
}

#[inline]
fn env_adsr(t: f32, a: f32, d: f32, s: f32, r: f32, dur: f32, sus_level: f32) -> f32 {
    if t < a {
        (t / a).clamp(0.0, 1.0)
    } else if t < a + d {
        1.0 - ((t - a) / d).clamp(0.0, 1.0) * (1.0 - sus_level)
    } else if t < dur - r {
        sus_level * s
    } else if t < dur {
        sus_level * s * ((dur - t) / r).clamp(0.0, 1.0)
    } else {
        0.0
    }
}

// cheap deterministic noise via LCG hash
#[inline]
fn hash_noise(i: usize, seed: u32) -> f32 {
    let h = i.wrapping_mul(1103515245).wrapping_add(seed as usize) >> 16 & 0x7FFF;
    h as f32 / 16383.5 * 2.0 - 1.0
}

// ---------------------------------------------------------------------------
// Synth helpers (loop / clamp / wav_bytes scaffolding)
// ---------------------------------------------------------------------------

#[inline]
fn sine(freq: f32, t: f32) -> f32 {
    (std::f32::consts::TAU * freq * t).sin()
}

fn decay(t: f32, rate: f32) -> f32 {
    (-t * rate).exp()
}

fn render(dur: f32, mut f: impl FnMut(f32, usize) -> f32) -> Vec<u8> {
    let n = (SR as f32 * dur) as usize;
    let mut out = Vec::with_capacity(n);
    for i in 0..n {
        let t = i as f32 / SR as f32;
        out.push(f(t, i));
    }
    wav_bytes(&out, SR)
}

