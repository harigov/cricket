/// Once-per-match / once-per-innings lifecycle flags for phase commentary.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct CommentaryLifecycle {
    pub match_fp: Option<MatchFingerprint>,
    /// Set at every match-session reset; consumed when the welcome line is dispatched.
    pub match_intro_pending: bool,
    pub welcome_played: bool,
    /// While true, non-welcome commentary is deferred so the opening line is not talked over.
    pub intro_open: bool,
    pub deliveries_completed: u32,
    /// Innings number for which `innings_break` has already been called.
    pub innings_break_played_for: u8,
}

/// Priority for the commentary scheduler (lower = higher priority).
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum CommentaryPriority {
    /// Ball-result action lines (six, bowled, dot, …) — never displaced.
    Result = 0,
    /// Phase transitions (over end, innings break, match result).
    Phase = 1,
    /// Opening welcome — once per match, lowest priority.
    Welcome = 2,
}

#[derive(Clone, Debug)]
struct ScheduledCommentary {
    category: String,
    variant: Option<usize>,
    priority: CommentaryPriority,
}

/// Pending lead call waiting for a free audio slot (result beats phase beats welcome).
#[derive(Resource, Default)]
struct CommentaryScheduler {
    pending: Option<ScheduledCommentary>,
}

/// Tracks whether we are inside a `ResultPause` we have already processed
